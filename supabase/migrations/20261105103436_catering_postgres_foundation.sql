CREATE VIEW public.order_payment_summary WITH (security_invoker=true) AS
SELECT
    o.id AS order_id,
    o.currency,
    o.total_minor,
    coalesce(sum(CASE WHEN p.kind = 'receipt' THEN p.amount_minor END), 0)::bigint AS received_minor,
    coalesce(sum(CASE WHEN p.kind = 'refund' THEN p.amount_minor END), 0)::bigint AS refunded_minor,
    coalesce(sum(CASE WHEN p.kind = 'receipt' THEN p.amount_minor ELSE -p.amount_minor END), 0)::bigint
        AS net_paid_minor,
    (o.total_minor
        - coalesce(sum(CASE WHEN p.kind = 'receipt' THEN p.amount_minor ELSE -p.amount_minor END), 0))::bigint
        AS balance_due_minor
FROM public.orders AS o
LEFT JOIN public.payments AS p ON p.order_id = o.id
GROUP BY o.id;
CREATE VIEW public.equipment_stock WITH (security_invoker=true) AS
SELECT
    i.id AS equipment_item_id,
    i.name,
    i.category,
    coalesce(sum(CASE m.movement_type
        WHEN 'purchase' THEN m.quantity
        WHEN 'return' THEN m.quantity
        WHEN 'adjustment_in' THEN m.quantity
        WHEN 'dispatch' THEN -m.quantity
        WHEN 'write_off' THEN -m.quantity
        WHEN 'adjustment_out' THEN -m.quantity
        ELSE 0 END), 0)::bigint AS on_hand,
    coalesce(sum(CASE m.movement_type
        WHEN 'dispatch' THEN m.quantity
        WHEN 'return' THEN -m.quantity
        WHEN 'lost_at_event' THEN -m.quantity
        ELSE 0 END), 0)::bigint AS out_at_events
FROM public.equipment_items AS i
LEFT JOIN public.equipment_movements AS m ON m.equipment_item_id = i.id
GROUP BY i.id;
CREATE VIEW public.equipment_out_by_order WITH (security_invoker=true) AS
SELECT
    equipment_item_id,
    order_id,
    sum(CASE movement_type WHEN 'dispatch' THEN quantity ELSE -quantity END)::bigint AS quantity_out
FROM public.equipment_movements
WHERE order_id IS DISTINCT FROM NULL
GROUP BY equipment_item_id, order_id;
CREATE VIEW public.ingredient_batch_stock WITH (security_invoker=true) AS
SELECT
    b.id AS batch_id,
    b.ingredient_id,
    i.name AS ingredient_name,
    i.base_unit,
    b.lot_code,
    b.received_on,
    b.expires_on,
    coalesce(sum(CASE
        WHEN m.movement_type IN ('receipt', 'adjustment_in') THEN m.quantity
        WHEN m.movement_type IS NULL THEN 0
        ELSE -m.quantity END), 0)::bigint AS on_hand
FROM public.ingredient_batches AS b
JOIN public.ingredients AS i ON i.id = b.ingredient_id
LEFT JOIN public.ingredient_movements AS m ON m.batch_id = b.id
GROUP BY b.id, i.id;
CREATE VIEW public.ingredient_stock WITH (security_invoker=true) AS
SELECT
    i.id AS ingredient_id,
    i.name,
    i.base_unit,
    i.reorder_level,
    coalesce(sum(CASE WHEN s.expires_on IS NULL OR s.expires_on >= (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Jerusalem')::date
                      THEN s.on_hand END), 0)::bigint AS usable_on_hand,
    coalesce(sum(CASE WHEN s.expires_on < (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Jerusalem')::date THEN s.on_hand END), 0)::bigint AS expired_on_hand
FROM public.ingredients AS i
LEFT JOIN public.ingredient_batch_stock AS s ON s.ingredient_id = i.id
GROUP BY i.id;

CREATE FUNCTION public.orders_status_transition_fn() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = '' AS $fn$
BEGIN

    IF NEW.status IS DISTINCT FROM OLD.status
 AND NOT ((OLD.status = 'draft' AND NEW.status = 'pending_approval')
       OR (OLD.status = 'pending_approval' AND NEW.status IN ('approved', 'rejected'))) THEN RAISE EXCEPTION 'invalid order status transition' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END; $fn$;
REVOKE ALL ON FUNCTION public.orders_status_transition_fn() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER orders_status_transition BEFORE UPDATE OF status ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.orders_status_transition_fn();


CREATE FUNCTION public.deliveries_food_requires_delivery_order_fn() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = '' AS $fn$
DECLARE order_fulfillment text;
BEGIN
    IF NEW.purpose = 'food_drop_off' THEN
        -- SHARE blocks a concurrent fulfillment change, not FK checks. A hidden order leaves NULL and fails.
        SELECT fulfillment_type INTO order_fulfillment FROM public.orders WHERE id = NEW.order_id FOR SHARE;
        IF order_fulfillment IS DISTINCT FROM 'delivery' THEN RAISE EXCEPTION 'food drop-off requires a delivery order' USING ERRCODE='23514'; END IF;
    END IF;
    RETURN NEW;
END; $fn$;
REVOKE ALL ON FUNCTION public.deliveries_food_requires_delivery_order_fn() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER deliveries_food_requires_delivery_order BEFORE INSERT ON public.deliveries
FOR EACH ROW EXECUTE FUNCTION public.deliveries_food_requires_delivery_order_fn();


CREATE FUNCTION public.payments_refund_targets_receipt_fn() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = '' AS $fn$
DECLARE target_kind text;
BEGIN
    IF NEW.kind = 'refund' THEN
        -- A hidden or missing receipt leaves NULL and fails.
        SELECT kind INTO target_kind FROM public.payments WHERE id = NEW.refund_of_payment_id FOR NO KEY UPDATE;
        IF target_kind IS DISTINCT FROM 'receipt' THEN RAISE EXCEPTION 'a refund must reference a receipt' USING ERRCODE='23514'; END IF;
    END IF;
    RETURN NEW;
END; $fn$;
REVOKE ALL ON FUNCTION public.payments_refund_targets_receipt_fn() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER payments_refund_targets_receipt BEFORE INSERT ON public.payments
FOR EACH ROW EXECUTE FUNCTION public.payments_refund_targets_receipt_fn();


CREATE FUNCTION public.payments_refund_within_receipt_fn() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = '' AS $fn$
DECLARE receipt_amount bigint;
BEGIN
    IF NEW.kind = 'refund' THEN
        SELECT amount_minor INTO receipt_amount FROM public.payments WHERE id = NEW.refund_of_payment_id FOR NO KEY UPDATE;
        -- IS NOT TRUE: an unknown receipt amount must reject, not accept.
        IF (NEW.amount_minor
            + (SELECT coalesce(sum(amount_minor), 0) FROM public.payments
               WHERE refund_of_payment_id = NEW.refund_of_payment_id)
            <= receipt_amount) IS NOT TRUE THEN RAISE EXCEPTION 'refunds exceed the original receipt' USING ERRCODE='23514'; END IF;
    END IF;
    RETURN NEW;
END; $fn$;
REVOKE ALL ON FUNCTION public.payments_refund_within_receipt_fn() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER payments_refund_within_receipt BEFORE INSERT ON public.payments
FOR EACH ROW EXECUTE FUNCTION public.payments_refund_within_receipt_fn();


