-- Supabase/Postgres port of SQLite migrations 0001-0003.
-- Fresh catering project only. No flight-project objects or data are touched.
-- No customer data is imported. Hand-maintained: supabase/build_foundation.py refuses to regenerate it.
--
-- Transactions: no BEGIN/COMMIT here on purpose. The migration runner owns the transaction that
-- covers this file and its history row; an inner COMMIT could separate the two.
--   Local:  supabase db reset
--   Remote: supabase db push --remote --yes   (only once the new catering project is confirmed)
--   Never use a bare `psql -f`; if psql is unavoidable add --single-transaction -v ON_ERROR_STOP=1.
--
-- Business dates: expiry, receipt and stock dates are evaluated in Asia/Jerusalem. SQLite used UTC,
-- so behaviour near midnight intentionally differs from the SQLite tests.
--
-- Concurrency: the triggers assume READ COMMITTED, where each statement after a lock wait gets a
-- fresh snapshot. REPEATABLE READ writers would check against a stale snapshot.
--   FOR NO KEY UPDATE on the row that serializes a check: receipt, equipment item, batch. It conflicts
--     with itself but not with FK KEY SHARE. Every trigger on a table takes the same mode first,
--     because a SHARE lock later upgraded by two sessions would deadlock.
--   FOR SHARE on parents read for a guard: order fulfillment, ingredient unit.
-- Row locks need the UPDATE privilege and UPDATE policy, so authenticated deliberately keeps UPDATE on
-- the ledgers; append-only triggers reject the actual UPDATE, DELETE and TRUNCATE.
--
-- Hidden rows: triggers run as the invoker, so RLS applies to their reads. A hidden parent fails
-- closed below. Only rows hidden from a parent's aggregate or EXISTS (a partly visible ledger) cannot
-- be detected, which is safe only while every writer sees everything, as catering_managers does.
-- Before adding a narrower policy, redesign these checks; foundation.sql pins the policy list.
revoke create on schema public from public, anon, authenticated;
alter default privileges in schema public revoke all on tables from anon, authenticated;
alter default privileges in schema public revoke all on sequences from anon, authenticated;
alter default privileges in schema public revoke all on functions from anon, authenticated;

CREATE TABLE public.customers (
    id bigint generated by default as identity PRIMARY KEY,
    full_name   TEXT NOT NULL CHECK (length(trim(full_name)) > 0),
    email       TEXT  UNIQUE CHECK (email IS NULL OR email LIKE '%_@_%'),
    phone       TEXT CHECK (phone IS NULL OR length(trim(phone)) > 0),
    created_at timestamptz NOT NULL DEFAULT now()
                ,
    updated_at timestamptz NOT NULL DEFAULT now()
                ,
    CHECK (email IS NOT NULL OR phone IS NOT NULL)
);

