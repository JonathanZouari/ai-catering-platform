const HASH_8 = '8'.repeat(64);
const HASH_9 = '9'.repeat(64);
const PAYLOAD_8 = '{"items": {"d1": "2", "d5": "1.5"},  "b":"שלום"}';
const PAYLOAD_9 = '{"items": {"d10": "1"}}';

// Comparable with the old document: prices and steps left it, and allergens are checked separately.
function legacyView(dish) {
  const { price, step, allergens, allergenStatuses, ...rest } = dish;
  return rest;
}

export async function checkCatalogNormalization(db, { migrationsDir = DEFAULT_DIR } = {}) {
  const apply = await prepareOldSchema(db, migrationsDir);

  // ---- The old world: orders 8 and 9 through the old RPC, an image and a staff-made dish ----
  await db.exec(`
    select setval('public.orders_id_seq', 7);
    update public.dishes set image_path='dishes/d3/old-image.png' where id='d3';
    insert into storage.objects(bucket_id,name) values('dish-images','dishes/d3/old-image.png');
    insert into public.dishes(id,metadata,price_minor,step_milli) values('staff-dish',
      '{"id":"staff-dish","categoryId":"specials","name":"מנת צוות","unit":"kg","price":999,"futureKey":"keep"}',
      5000, 500);`);
  assert.equal((await submit(db, HASH_8, PAYLOAD_8, order())).saved.order.id, 8);
  assert.equal((await submit(db, HASH_9, PAYLOAD_9, ORDER_9)).saved.order.id, 9);
  const submissionRows = () => db.query('select token_hash,order_id,payload from public.order_submissions order by order_id').then(r => r.rows);
  const orderCount = () => db.query('select count(*)::int n from public.orders').then(r => r.rows[0].n);
  const before = {
    receipt8: await read(db, HASH_8),
    receipt9: await read(db, HASH_9),
    submissions: await submissionRows(),
    items: (await db.query(`select order_id,dish_id,name,unit,quantity_milli,unit_price_minor,line_total_minor
                            from public.order_items order by order_id,dish_id`)).rows,
    dishes: (await db.query('select id,metadata,price_minor,step_milli from public.dishes order by length(id),id')).rows,
    zones: (await db.query('select city,fee_minor from public.delivery_zones order by fee_minor,city')).rows,
    catalog: await catalog(db),
    orders: await orderCount(),
  };

  // ---- An unreadable dish stops the migration and changes nothing ----
  await db.exec(`insert into public.dishes values('bad-unit','{"categoryId":"mains","name":"x","unit":"box"}',1,1)`);
  await assert.rejects(apply(), /fix these dishes first: bad-unit/);
  assert.equal((await db.query(`select data_type from information_schema.columns
    where table_schema='public' and table_name='dishes' and column_name='id'`)).rows[0].data_type, 'text');
  assert.equal((await db.query(`select to_regclass('public.allergens') r`)).rows[0].r, null);
  await db.exec(`delete from public.dishes where id='bad-unit'`);

  await apply();

  // ---- Keys ----
  const types = (await db.query(`select table_name, column_name, data_type, is_identity
    from information_schema.columns where table_schema='public' and (
      (table_name in ('dishes','delivery_zones','dish_categories','allergens') and column_name='id')
      or column_name in ('dish_id','allergen_id','category_id')
      or (table_name='order_submissions' and column_name='order_id'))`)).rows;
  assert.ok(types.length >= 9);
  assert.ok(types.every(t => t.data_type === 'bigint'), JSON.stringify(types));
  assert.ok(types.filter(t => t.column_name === 'id').every(t => t.is_identity === 'YES'));
  const textKeys = await db.query(`select c.conrelid::regclass::text t, c.contype::text from pg_constraint c
    join pg_attribute a on a.attrelid=c.conrelid and a.attnum=any(c.conkey)
    where c.contype in ('f','p') and a.atttypid='text'::regtype and c.conrelid = any(array[
      'public.dishes','public.delivery_zones','public.order_items','public.order_submissions',
      'public.dish_categories','public.dish_dietary','public.allergens','public.dish_allergens']::regclass[])`);
  assert.deepEqual(textKeys.rows, [], 'no primary or foreign key may use a text column');
  const constraint = async (name, type) => (await db.query(`select pg_get_constraintdef(oid) d from pg_constraint
    where conrelid=$1::regclass and contype=$2`, [name, type])).rows.map(r => r.d);
  assert.deepEqual(await constraint('public.order_submissions', 'p'), ['PRIMARY KEY (order_id)']);
  assert.deepEqual(await constraint('public.order_submissions', 'u'), ['UNIQUE (token_hash)']);
  await assert.rejects(db.exec(`insert into public.order_submissions(token_hash,order_id,payload) values('${HASH_8}',1,'{}')`), /duplicate key/);
  await assert.rejects(db.exec(`insert into public.order_submissions(token_hash,order_id,payload) values('z',8,'{}')`), /duplicate key/);

  // Natural order: d2 before d10.
  const mapping = (await db.query('select id::int,legacy_code from public.dishes order by id')).rows;
  assert.deepEqual(mapping.map(m => m.legacy_code), before.dishes.map(d => d.id));
  assert.deepEqual(mapping.map(m => m.id), before.dishes.map((_, index) => index + 1));
  assert.equal(mapping[9].legacy_code, 'd10');
  const idOf = Object.fromEntries(mapping.map(m => [m.legacy_code, m.id]));

  // New rows must not collide with migrated keys, and need nothing but the sequence grant.
  await asRole(db, 'authenticated', OWNER, `
    insert into public.dishes(legacy_code,category_id,name,pricing_unit,price_minor,step_milli)
      values('new-dish',1,'חדש','kg',100,500);
    insert into public.delivery_zones(city,fee_minor) values('עיר חדשה',1);
    delete from public.delivery_zones where city='עיר חדשה';`);
  assert.equal((await db.query(`select id::int from public.dishes where legacy_code='new-dish'`)).rows[0].id, mapping.length + 1);
  await db.exec(`delete from public.dishes where legacy_code='new-dish'`);

  // ---- Zones: same cities and fees, city still unique ----
  assert.deepEqual((await db.query('select city,fee_minor from public.delivery_zones order by id')).rows, before.zones);
  await assert.rejects(db.exec(`insert into public.delivery_zones(city,fee_minor) values('רמת גן',1)`), /duplicate key/);

  // ---- History: receipts, hashes and payload bytes are identical ----
  assert.deepEqual(await read(db, HASH_8), before.receipt8);
  assert.deepEqual(await read(db, HASH_9), before.receipt9);
  assert.deepEqual((await read(db, HASH_8)).items.map(i => i.name), ['חומוס', 'עוף']);
  assert.deepEqual(await submissionRows(), before.submissions);
  assert.equal(await orderCount(), before.orders);
  const items = (await db.query(`select i.order_id,d.legacy_code as dish_id,i.name,i.unit,i.quantity_milli,
      i.unit_price_minor,i.line_total_minor from public.order_items i join public.dishes d on d.id=i.dish_id
      order by i.order_id,d.legacy_code`)).rows;
  assert.deepEqual(items, before.items);

  // Retries: identical payload replays with no write, another one conflicts, wrong token finds nothing.
  const replay = await submit(db, HASH_8, PAYLOAD_8, order());
  assert.equal(replay.outcome, 'existing');
  assert.deepEqual(replay.saved, before.receipt8);
  assert.deepEqual(await submit(db, HASH_8, '{"other":1}', order()), { outcome: 'conflict' });
  assert.equal(await read(db, 'b'.repeat(64), 8), null);
  assert.equal(await read(db, HASH_8, 9), null);
  assert.equal(await orderCount(), before.orders);

  // ---- The old document is private and recoverable; the live table no longer holds it ----
  const columns = (await db.query(`select column_name from information_schema.columns
    where table_schema='public' and table_name='dishes'`)).rows.map(c => c.column_name);
  assert.ok(!columns.includes('metadata'));
  assert.deepEqual(columns.filter(c => /price/.test(c)), ['price_minor'], 'one authoritative catalog price');
  const backup = (await db.query(`select legacy_code as id,metadata,price_minor_at_migration as price_minor,
    step_milli_at_migration as step_milli from private.dish_metadata_backup order by dish_id`)).rows;
  assert.deepEqual(backup, before.dishes);
  assert.equal(backup.find(b => b.id === 'staff-dish').metadata.futureKey, 'keep');
  for (const role of ['anon', 'authenticated', 'service_role']) {
    await assert.rejects(asRole(db, role, OWNER, 'select * from private.dish_metadata_backup'), /permission denied/);
  }

  // ---- Typed values ----
  const d9 = (await db.query(`select d.name,d.pricing_unit,d.per_guest::text,c.legacy_code as category,d.price_minor
    from public.dishes d join public.dish_categories c on c.id=d.category_id where d.legacy_code='d9'`)).rows[0];
  assert.deepEqual(d9, { name: 'פילה סלמון בלימון', pricing_unit: 'item', per_guest: '0.6', category: 'fish', price_minor: 9800 });
  assert.equal((await db.query(`select name from public.dish_categories where legacy_code='specials'`)).rows[0].name, 'specials');
  // The document's 999 was never the quoted price; price_minor stays authoritative.
  assert.equal((await db.query(`select price_minor from public.dishes where legacy_code='staff-dish'`)).rows[0].price_minor, 5000);

  // ---- Dietary and allergen statuses ----
  const dietary = code => db.query(`select kashrut_class,is_vegetarian,is_vegan,verified_at from public.dish_dietary
    where dish_id=$1`, [idOf[code]]).then(r => r.rows[0]);
  assert.deepEqual(await dietary('d3'), { kashrut_class: 'dairy', is_vegetarian: true, is_vegan: false, verified_at: null });
  assert.deepEqual(await dietary('staff-dish'), { kashrut_class: null, is_vegetarian: null, is_vegan: null, verified_at: null });
  const stored = code => db.query(`select a.name,da.status from public.dish_allergens da
    join public.allergens a on a.id=da.allergen_id where da.dish_id=$1`, [idOf[code]])
    .then(r => Object.fromEntries(r.rows.map(s => [s.name, s.status])));
  assert.deepEqual(await stored('d8'), {}, 'a NULL list stays unknown through missing rows');
  assert.deepEqual(await stored('staff-dish'), {}, 'a missing list stays unknown');
  assert.deepEqual(await stored('d2'), {}, 'an empty list is not evidence of free');
  assert.deepEqual(await stored('d3'), { חלב: 'contains', אגוזים: 'contains' });
  assert.equal((await db.query(`select count(*)::int n from public.dish_allergens where status<>'contains'`)).rows[0].n, 0,
    'the migration never infers free');
  await assert.rejects(db.exec(`update public.dish_dietary set is_vegan=true,is_vegetarian=false where dish_id=1`), /check constraint/);
  await assert.rejects(db.exec(`update public.dish_allergens set status='maybe' where dish_id=1`), /check constraint/);

  // ---- The API projection equals the old catalog, except where the old data had no statuses ----
  const after = await catalog(db);
  assert.deepEqual(Object.keys(after).sort(), ['dishes', 'zones']);
  assert.deepEqual(after.zones, before.catalog.zones);
  assert.deepEqual(after.dishes.map(d => d.id), before.catalog.dishes.map(d => d.id));
  for (const [index, dish] of after.dishes.entries()) {
    const old = before.catalog.dishes[index];
    assert.deepEqual(Object.keys(dish).sort(), ['id', 'metadata', 'price_minor', 'step_milli']);
    assert.equal(dish.price_minor, old.price_minor);
    assert.equal(dish.step_milli, old.step_milli);
    assert.ok(!('price' in dish.metadata) && !('step' in dish.metadata), 'no second copy of the price');
    // Every old "contains" survives as a status; nothing else is claimed.
    const contains = dish.metadata.allergenStatuses.filter(s => s.status === 'contains').map(s => s.name).sort();
    assert.deepEqual(contains, [...(old.metadata.allergens ?? [])].sort(), dish.id);
    assert.deepEqual(dish.metadata.allergenStatuses.map(s => s.name), COMMON, dish.id);
    assert.ok(dish.metadata.allergenStatuses.every(s => s.status !== 'free'), dish.id);
    assert.equal(dish.metadata.allergens, null, 'a partial list must not read as complete');
    if (dish.id === 'staff-dish') continue;
    assert.deepEqual(legacyView(dish.metadata), legacyView(old.metadata), dish.id);
  }
  const byId = Object.fromEntries(after.dishes.map(d => [d.id, d.metadata]));
  assert.deepEqual(byId.d2.allergenStatuses, COMMON.map(name => ({ name, status: 'unknown' })));
  assert.deepEqual(byId.d8.allergenStatuses, COMMON.map(name => ({ name, status: 'unknown' })));
  assert.equal(statusesOf(byId.d3)['חלב'], 'contains');
  assert.equal(statusesOf(byId.d3)['גלוטן'], 'unknown');
  assert.equal(byId['staff-dish'].vegan, null);
  assert.equal(byId['staff-dish'].kashrut, null);
  assert.equal(byId['staff-dish'].description, '');

  await db.transaction(async tx => {
    const metadataOf = async code => (await tx.query('select public.customer_catalog() as c')).rows[0].c
      .dishes.find(d => d.id === code).metadata;
    // Only the owner's complete record produces the old-style list, or an explicit "none".
    await tx.query(`insert into public.dish_allergens(dish_id,allergen_id,status)
      select $1::bigint, a.id, 'free' from public.allergens a
      on conflict (dish_id,allergen_id) do nothing`, [idOf.d3]);
    assert.deepEqual((await metadataOf('d3')).allergens.sort(), ['אגוזים', 'חלב'].sort());
    await tx.query(`insert into public.dish_allergens(dish_id,allergen_id,status)
      select $1::bigint, a.id, 'free' from public.allergens a`, [idOf.d2]);
    assert.deepEqual((await metadataOf('d2')).allergens, []);
    // A new allergen makes every completed record unknown again.
    await tx.exec(`insert into public.allergens(name) values('סויה')`);
    assert.equal((await metadataOf('d2')).allergens, null);
    assert.equal(statusesOf(await metadataOf('d2'))['סויה'], 'unknown');
    assert.equal(statusesOf(await metadataOf('d2'))['חלב'], 'free');
    // An empty allergen list claims nothing either.
    await tx.exec('delete from public.dish_allergens; delete from public.allergens;');
    assert.equal((await metadataOf('d2')).allergens, null);
    await tx.rollback();
  });

  // ---- Availability: a withdrawn dish cannot be quoted, while its history stays intact ----
  assert.equal((await db.query('select bool_and(is_available) ok from public.dishes')).rows[0].ok, true);
  await db.exec(`update public.dishes set is_available=false where legacy_code='d10'`);
  assert.ok(!(await catalog(db)).dishes.some(d => d.id === 'd10'));
  assert.deepEqual(await submit(db, 'f'.repeat(64), '{"x":1}', order({ ...ORDER_9, street: '', city: '' })), { outcome: 'price_changed' });
  assert.deepEqual(await read(db, HASH_9), before.receipt9, 'a receipt does not depend on availability');
  const retried = await submit(db, HASH_9, PAYLOAD_9, ORDER_9);
  assert.equal(retried.outcome, 'existing', 'a retry of a saved order still succeeds');
  assert.deepEqual(retried.saved, before.receipt9);
  await db.exec(`update public.dishes set is_available=true where legacy_code='d10'`);

  // ---- New submissions: deterministic prices, stale quotes and atomic failure ----
  const fresh = await submit(db, 'a'.repeat(64), '{"new":1}', order());
  assert.equal(fresh.outcome, 'created');
  assert.equal(fresh.saved.order.id, 10);
  assert.deepEqual(fresh.saved.items.map(i => i.name), ['חומוס', 'עוף']);
  assert.deepEqual((await db.query(`select dish_id::int from public.order_items where order_id=10 order by 1`)).rows,
    [{ dish_id: idOf.d1 }, { dish_id: idOf.d5 }]);
  const stale = item => ({ items: [{ ...order().items[1], ...item }] });
  assert.deepEqual(await submit(db, 'c'.repeat(64), '{}', order(stale({ unit_price_minor: 1 }))), { outcome: 'price_changed' });
  assert.deepEqual(await submit(db, 'c'.repeat(64), '{}', order(stale({ dish_id: 'nope' }))), { outcome: 'price_changed' });
  assert.deepEqual(await submit(db, 'c'.repeat(64), '{}', order(stale({ dish_id: String(idOf.d1) }))), { outcome: 'price_changed' },
    'database keys are not accepted as dish codes');
  assert.deepEqual(await submit(db, 'c'.repeat(64), '{}', order({ delivery_fee_minor: 1 })), { outcome: 'price_changed' });
  const counted = async () => (await db.query('select (select count(*) from public.orders)::int o, (select count(*) from public.customers)::int c')).rows[0];
  const held = await counted();
  await assert.rejects(submit(db, 'e'.repeat(64), '{}', order({ subtotal_minor: 28000, total_minor: 34000 })), /do not add up/);
  assert.deepEqual(await counted(), held, 'a failed submission leaves nothing behind');

  // ---- Storage paths still resolve through the code ----
  assert.equal((await db.query(`select image_path from public.dishes where legacy_code='d3'`)).rows[0].image_path, 'dishes/d3/old-image.png');
  assert.equal((await db.query(`select count(*)::int n from storage.objects where name='dishes/d3/old-image.png'`)).rows[0].n, 1);
  await assert.rejects(db.exec(`update public.dishes set image_path='dishes/d2/x.png' where legacy_code='d3'`), /dishes_image_path_check/);
  const imageChecks = (await db.query(`select conname from pg_constraint
    where conrelid='public.dishes'::regclass and pg_get_constraintdef(oid) like '%image_path%'`)).rows;
  assert.deepEqual(imageChecks, [{ conname: 'dishes_image_path_check' }], 'only the code-based image check remains');
  await assert.rejects(db.exec(`update public.dishes set legacy_code='renamed' where legacy_code='d3'`), /cannot change/);
  await asRole(db, 'authenticated', OWNER, `insert into storage.objects(bucket_id,name) values('dish-images','dishes/d1/new.png')`);
  await assert.rejects(asRole(db, 'authenticated', OWNER,
    `insert into storage.objects(bucket_id,name) values('dish-images','dishes/1/numeric-key.png')`), /row-level security/);
  await assert.rejects(asRole(db, 'authenticated', OWNER,
    `insert into storage.objects(bucket_id,name) values('dish-images','dishes/missing/new.png')`), /row-level security/);

  // ---- Access ----
  const NEW_TABLES = ['dish_categories', 'dish_dietary', 'allergens', 'dish_allergens'];
  const rls = (await db.query(`select bool_and(rowsecurity) ok from pg_tables where schemaname='public'`)).rows[0];
  assert.equal(rls.ok, true, 'every public table uses RLS');
  for (const table of NEW_TABLES) {
    await assert.rejects(asRole(db, 'anon', {}, `select * from public.${table}`), /permission denied/);
    assert.equal((await asRole(db, 'authenticated', FORGED, `select * from public.${table}`))[0].rows.length, 0, 'user_metadata grants nothing');
    assert.equal((await asRole(db, 'authenticated', MANAGER, `select * from public.${table}`))[0].rows.length, 0, 'only the owner has access');
    const service = await db.query(`select
      has_table_privilege('service_role','public.${table}','select') as can_read,
      has_table_privilege('service_role','public.${table}','insert,update,delete') as can_write`);
    assert.deepEqual(service.rows[0], { can_read: true, can_write: false });
  }
  for (const claims of [MANAGER, FORGED]) {
    await assert.rejects(asRole(db, 'authenticated', claims, `insert into public.allergens(name) values('אסור')`), /row-level security/);
  }
  const ownerRows = await asRole(db, 'authenticated', OWNER, 'select * from public.dish_dietary');
  assert.equal(ownerRows[0].rows.length, mapping.length);

  for (const call of ['select public.customer_catalog()', "select public.customer_order_read('h')",
    "select public.customer_order_submit('h','{}','{}'::jsonb)"]) {
    await assert.rejects(asRole(db, 'anon', {}, call), /permission denied for function/);
    await assert.rejects(asRole(db, 'authenticated', OWNER, call), /permission denied for function/);
  }
  const functions = (await db.query(`select p.proname, p.prosecdef, p.proconfig from pg_proc p
    where p.pronamespace='public'::regnamespace and p.proname in
      ('customer_catalog','customer_order_read','customer_order_submit','dishes_legacy_code_immutable_fn')`)).rows;
  assert.equal(functions.length, 4);
  for (const fn of functions) {
    assert.equal(fn.prosecdef, false, fn.proname);
    assert.deepEqual(fn.proconfig, ['search_path=""'], fn.proname);
  }
  // Published tables still accept writes: they kept a replica identity through the swap.
  const published = (await db.query(`select tablename from pg_publication_tables where pubname='supabase_realtime'`)).rows.map(r => r.tablename);
  for (const table of ['dishes', 'delivery_zones', 'order_items']) assert.ok(published.includes(table), table);
  await db.exec(`update public.dishes set price_minor=price_minor where id=1;
    update public.delivery_zones set fee_minor=fee_minor where id=1;
    update public.order_items set name=name where order_id=8;`);
}

// Data the seed never had: a name outside the common six and contradictory or malformed facts.
export async function checkCatalogDrift(db, { migrationsDir = DEFAULT_DIR } = {}) {
  const apply = await prepareOldSchema(db, migrationsDir);
  await db.exec(`insert into public.dishes(id,metadata,price_minor,step_milli) values
    ('soy-dish','{"categoryId":"mains","name":"טופו","unit":"kg","vegetarian":false,"vegan":true,"kashrut":"other","allergens":[" סויה ","סויה"]}',1000,500),
    ('text-flag','{"categoryId":"mains","name":"מחרוזת","unit":"tray","vegetarian":"true","allergens":null}',1000,1000);`);
  await apply();
  const dishes = Object.fromEntries((await catalog(db)).dishes.map(d => [d.id, d.metadata]));

  // A new name becomes one allergen, known only for the dish that listed it.
  assert.equal(statusesOf(dishes.d2)['סויה'], 'unknown');
  assert.equal(statusesOf(dishes['soy-dish'])['סויה'], 'contains');
  assert.equal(statusesOf(dishes['soy-dish'])['חלב'], 'unknown');
  assert.equal((await db.query(`select count(*)::int n from public.allergens where name like '%סויה%'`)).rows[0].n, 1);

  // Contradictory and malformed facts become unknown, never a guess.
  assert.deepEqual([dishes['soy-dish'].vegetarian, dishes['soy-dish'].vegan, dishes['soy-dish'].kashrut], [null, null, null]);
  assert.equal(dishes['text-flag'].vegetarian, null);
  // The raw values stay recoverable.
  const raw = (await db.query(`select metadata from private.dish_metadata_backup where legacy_code='soy-dish'`)).rows[0].metadata;
  assert.equal(raw.kashrut, 'other');
  assert.deepEqual(raw.allergens, [' סויה ', 'סויה']);
}

