"""Synthetic leads for the demo. Not real people and not real outcomes.

The app has no real lead data yet, so the outcome of each closed lead is drawn from the
made-up rule in `win_probability`. A model trained on this data can only learn that rule back.

Writes supabase/seed_leads.sql. Run from backend/:
    uv run python -m scripts.sample_leads
"""

import random
from math import exp
from pathlib import Path

SEED_FILE = Path(__file__).resolve().parents[2] / "supabase" / "seed_leads.sql"
LEAD_COUNT = 400
RANDOM_SEED = 20261116

# Each value is the made-up effect of the category on the log-odds of a purchase.
EVENT_TYPES = {
    "יום הולדת": 0.0,
    "אירוע משפחתי": 0.2,
    "בר או בת מצווה": 0.5,
    "ארוחת שבת": 0.3,
    "יום נישואין": 0.1,
    "חגיגה פרטית": -0.1,
    "אחר": -0.4,
}
SOURCES = {"referral": 0.8, "google": 0.0, "instagram": -0.5, "website": 0.2}
OPEN_STATUSES = ("new", "contacted", "quoted")

FIRST_NAMES = (
    "נועה", "יעל", "תמר", "מיכל", "שירה", "רותם", "הילה", "ליאת", "אורית", "דנה",
    "יואב", "איתי", "עומר", "נדב", "רועי", "אלון", "גיל", "עידו", "אסף", "יונתן",
)  # fmt: skip
LAST_NAMES = (
    "כהן", "לוי", "מזרחי", "פרץ", "ביטון", "דהן", "אברהם", "פרידמן", "אזולאי", "חדד",
    "גבאי", "שפירא", "רוזן", "קליין", "סויסה", "בן דוד", "אוחיון", "וקנין", "גולן", "שחר",
)  # fmt: skip


def win_probability(lead: dict) -> float:
    """The made-up rule that decides which synthetic leads end in a purchase."""
    log_odds = (
        -0.3
        + 1.0 * lead["is_returning"]
        + SOURCES[lead["source"]]
        + EVENT_TYPES[lead["event_type"]]
        + 0.010 * (lead["budget_per_guest"] - 160)
        - 0.004 * (lead["guests"] - 60)
        + 0.012 * (lead["lead_days"] - 35)
    )
    return 1 / (1 + exp(-log_odds))


def generate(count: int = LEAD_COUNT, seed: int = RANDOM_SEED) -> list[dict]:
    """The same leads for the same arguments. `age_days` is how long ago the lead came in;
    `lead_days` is the gap between the inquiry and the event."""
    rng = random.Random(seed)  # noqa: S311 - sample data, not a security use
    leads = []
    for number in range(1, count + 1):
        is_closed = rng.random() < 0.6
        age_days = rng.randint(20, 180) if is_closed else rng.randint(0, 25)
        lead = {
            "full_name": f"{rng.choice(FIRST_NAMES)} {rng.choice(LAST_NAMES)}",
            # 555 numbers and example.com cannot reach a real person.
            "phone": f"050-555-{number:04d}",
            "email": f"lead{number:03d}@example.com",
            "event_type": rng.choice(tuple(EVENT_TYPES)),
            "guests": rng.randint(10, 150),
            "budget_per_guest": rng.randrange(80, 281, 5),
            "source": rng.choice(tuple(SOURCES)),
            "is_returning": rng.random() < 0.25,
            "age_days": age_days,
            # An open lead's event is still ahead.
            "lead_days": rng.randint(3, 120) if is_closed else rng.randint(age_days + 3, 120),
        }
        if is_closed:
            lead["status"] = "won" if rng.random() < win_probability(lead) else "lost"
        else:
            lead["status"] = rng.choice(OPEN_STATUSES)
        leads.append(lead)
    return leads


def to_sql(leads: list[dict]) -> str:
    rows = []
    for lead in leads:
        days_to_event = lead["lead_days"] - lead["age_days"]
        rows.append(
            f"  ('{lead['full_name']}', '{lead['phone']}', '{lead['email']}', "
            f"'{lead['event_type']}', current_date + {days_to_event}, {lead['guests']}, "
            f"{lead['budget_per_guest']}, '{lead['source']}', "
            f"{'true' if lead['is_returning'] else 'false'}, '{lead['status']}', "
            f"now() - interval '{lead['age_days']} days')"
        )
    return (
        # Every value below comes from the constants in this file, never from outside input.
        "-- SAMPLE DATA: synthetic leads, not real people. Generated by\n"  # noqa: S608
        "-- backend/scripts/sample_leads.py; edit the script, not this file.\n"
        "-- Dates are relative to the day the seed runs, so open leads have future events.\n"
        "-- Load with: supabase db query --linked -f supabase/seed_leads.sql\n\n"
        "do $$\nbegin\n"
        "  if exists (select 1 from public.leads) then\n"
        "    raise exception 'seed already loaded: public.leads is not empty';\n"
        "  end if;\nend $$;\n\n"
        "insert into public.leads (full_name, phone, email, event_type, event_date, guests, "
        "budget_per_guest, source, is_returning, status, created_at) values\n"
        + ",\n".join(rows)
        + ";\n"
    )


if __name__ == "__main__":
    SEED_FILE.write_text(to_sql(generate()), encoding="utf-8", newline="\n")
    print(f"Wrote {LEAD_COUNT} leads to {SEED_FILE}")
