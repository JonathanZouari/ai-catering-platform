CREATE FUNCTION public.equipment_movements_on_hand_not_negative_fn() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = '' AS $fn$
BEGIN
    IF NEW.movement_type IN ('dispatch', 'write_off', 'adjustment_out') THEN
        PERFORM 1 FROM public.equipment_items WHERE id=NEW.equipment_item_id FOR NO KEY UPDATE;
        -- A hidden item has no stock row; IS NOT TRUE turns that NULL into a rejection.
        IF ((SELECT on_hand FROM public.equipment_stock WHERE equipment_item_id = NEW.equipment_item_id)
            >= NEW.quantity) IS NOT TRUE THEN RAISE EXCEPTION 'not enough equipment on hand' USING ERRCODE='23514'; END IF;
    END IF;
    RETURN NEW;
END; $fn$;
REVOKE ALL ON FUNCTION public.equipment_movements_on_hand_not_negative_fn() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER equipment_movements_on_hand_not_negative BEFORE INSERT ON public.equipment_movements
FOR EACH ROW EXECUTE FUNCTION public.equipment_movements_on_hand_not_negative_fn();


CREATE FUNCTION public.equipment_movements_out_not_negative_fn() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = '' AS $fn$
BEGIN
    IF NEW.movement_type IN ('return', 'lost_at_event') THEN
        PERFORM 1 FROM public.equipment_items WHERE id=NEW.equipment_item_id FOR NO KEY UPDATE;
        IF NOT FOUND THEN RAISE EXCEPTION 'equipment item is not visible to this role' USING ERRCODE='23514'; END IF;
        IF coalesce((SELECT quantity_out FROM public.equipment_out_by_order
                     WHERE equipment_item_id = NEW.equipment_item_id AND order_id = NEW.order_id), 0)
           < NEW.quantity THEN RAISE EXCEPTION 'more equipment returned or lost than was dispatched for this order' USING ERRCODE='23514'; END IF;
    END IF;
    RETURN NEW;
END; $fn$;
