-- Catalog: dish categories, dishes, dietary info and allergens.
-- Mirrors backend/app/models/catalog.py (ADR 0002). Apply the same file to the dev and prod projects.
--
-- Access model: the browser never talks to these tables. The backend connects with a privileged
-- role and enforces authorization in services, so RLS is enabled with no policies and the Data API
-- roles get no grants (defense in depth).

create table public.dish_categories (
    id          uuid primary key default gen_random_uuid(),
    name        text not null unique,
    sort_order  integer not null default 0,
    is_active   boolean not null default true
);

create table public.dishes (
    id                 uuid primary key default gen_random_uuid(),
    category_id        uuid not null references public.dish_categories (id),
    name               text not null,
    description        text,
    image_path         text,                          -- Supabase Storage object path
    pricing_unit       varchar(16) not null
        constraint ck_dishes_pricing_unit
        check (pricing_unit in ('per_guest', 'per_tray', 'per_weight', 'per_item')),
    unit_price_agorot  integer not null
        constraint ck_dishes_price_non_negative check (unit_price_agorot >= 0),
    unit_label         text,                          -- OPEN #18
    currency           varchar(3) not null default 'ILS',  -- OPEN #17
    per_guest          double precision               -- PLACEHOLDER until quantity_rules (OPEN #3)
        constraint ck_dishes_per_guest_positive check (per_guest is null or per_guest > 0),
    qty_step           integer
        constraint ck_dishes_qty_step_positive check (qty_step is null or qty_step > 0),
    is_available       boolean not null default true,
    created_at         timestamptz not null default now(),
    updated_at         timestamptz not null default now()
);

create index ix_dishes_category_id on public.dishes (category_id);

-- 1:1 with dishes. Every null means "not provided" and must be shown as unknown, never as no.
create table public.dish_dietary (
    dish_id        uuid primary key references public.dishes (id) on delete cascade,
    kashrut_class  varchar(8)
        constraint ck_dish_dietary_kashrut check (kashrut_class in ('meat', 'dairy', 'pareve')),
    is_vegetarian  boolean,
    is_vegan       boolean,
    verified_at    timestamptz
);

-- The allergen list is maintained by the owner.
create table public.allergens (
    id    smallint generated by default as identity primary key,
    name  text not null unique
);

-- A missing row means unknown (Decision 9: unknown is never the same as free).
create table public.dish_allergens (
    dish_id      uuid not null references public.dishes (id) on delete cascade,
    allergen_id  smallint not null references public.allergens (id),
    status       varchar(8) not null
        constraint ck_dish_allergens_status check (status in ('contains', 'free', 'unknown')),
    primary key (dish_id, allergen_id)
);

create index ix_dish_allergens_allergen_id on public.dish_allergens (allergen_id);

-- Keep updated_at current for edits made outside the backend (e.g. the Supabase table editor).
create function public.set_updated_at() returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

revoke execute on function public.set_updated_at() from public, anon, authenticated;

create trigger trg_dishes_updated_at
    before update on public.dishes
    for each row execute function public.set_updated_at();

alter table public.dish_categories enable row level security;
alter table public.dishes          enable row level security;
alter table public.dish_dietary    enable row level security;
alter table public.allergens       enable row level security;
alter table public.dish_allergens  enable row level security;

revoke all on public.dish_categories, public.dishes, public.dish_dietary,
              public.allergens, public.dish_allergens
    from anon, authenticated;
