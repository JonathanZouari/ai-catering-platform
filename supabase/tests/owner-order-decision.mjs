// Owner decision RPC on real SQL in an isolated PGlite. No hosted database or credentials.
//   node supabase/tests/owner-order-decision.mjs
// Orders are created by the earlier migrations' RPC first, so the new migration is applied to
// existing data. PGlite is one connection: racing sessions are proven by the SQLite backend test
// and by the single compare-and-write UPDATE, not here.
// CATERING_PGLITE may point at another pglite/dist/index.js (for example from a worktree).
import assert from 'node:assert/strict';
import { mkdtemp, readdir, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';

const pgliteUrl = process.env.CATERING_PGLITE
  ? pathToFileURL(process.env.CATERING_PGLITE).href
  : new URL('../.test-tools/pglite/dist/index.js', import.meta.url).href;
const { PGlite } = await import(pgliteUrl);

const MIGRATIONS = new URL('../migrations/', import.meta.url);
const OWNER = { app_metadata: { role: 'catering_owner' } };
const UNTOUCHED = ['customers', 'addresses', 'events', 'order_items', 'order_submissions'];
const DECISION_COLUMNS = ['status', 'version', 'decided_at', 'decision_note', 'updated_at'];

const draft = (over = {}) => ({
  full_name: 'בדיקה', phone: '0501234567', street: 'רחוב 1', city: 'תל אביב-יפו',
  event_type: 'יום הולדת', event_date: '2030-01-10', adults: 10, children: 2,
  vegetarian_guests: 1, vegan_guests: 0, restricted_guests: 0, dietary_notes: '',
  fulfillment_type: 'delivery', requested_at: '2030-01-10T07:00:00Z',
  subtotal_minor: 28100, delivery_fee_minor: 6000, total_minor: 34100,
  items: [
    { dish_id: 'd5', name: 'עוף', unit: 'kg', quantity_milli: 1500, unit_price_minor: 7400, line_total_minor: 11100 },
    { dish_id: 'd1', name: 'חומוס', unit: 'tray', quantity_milli: 2000, unit_price_minor: 8500, line_total_minor: 17000 },
  ],
  ...over,
});

const tempRoot = resolve(tmpdir());
const dataDir = await mkdtemp(join(tempRoot, 'catering-decision-test-'));
let db = await PGlite.create(dataDir);

const asService = async (sql, params = []) => {
  await db.exec('set role service_role');
  try { return (await db.query(sql, params)).rows; } finally { await db.exec('reset role'); }
};
const asRole = (role, claims, sql) => db.transaction(async tx => {
  await tx.exec(`set local role ${role}`);
  await tx.query("select set_config('request.jwt.claims',$1,true)", [JSON.stringify(claims)]);
  return tx.exec(sql);
});
const decide = async (id, decision, version, note = '') => (await asService(
  'select public.owner_order_decide($1::bigint,$2,$3::bigint,$4) as r',
  [id, decision, version, note]))[0].r;
const read = async hash => (await asService('select public.customer_order_read($1) as r', [hash]))[0].r;
const table = async name => (await db.query(`select * from public.${name} order by 1, 2`)).rows;
const orders = async (columns = '*') => (await db.query(`select ${columns} from public.orders order by id`)).rows;
const frozenOrderColumns = 'id, customer_id, event_id, fulfillment_type, requested_at, delivery_address_id, '
  + 'currency, subtotal_minor, delivery_fee_minor, total_minor, submitted_at, created_at';
const policies = async () => (await db.query(`select schemaname, tablename, policyname, cmd, roles::text,
  qual, with_check from pg_policies order by 1, 2, 3`)).rows;
const everything = async () => {
  const out = { orders: await orders(), policies: await policies() };
  for (const name of UNTOUCHED) out[name] = await table(name);
  return out;
};

try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; grant usage on schema auth to anon, authenticated;
    create function auth.jwt() returns jsonb language sql stable as
      $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
    create schema storage;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id bigint generated by default as identity primary key,bucket_id text references storage.buckets(id),name text);
    alter table storage.objects enable row level security;
    grant usage on schema storage to authenticated;
    grant select,insert,update,delete on storage.objects to authenticated;
    grant usage on all sequences in schema storage to authenticated;
    create publication supabase_realtime;`);
  const names = (await readdir(MIGRATIONS)).filter(n => n.endsWith('.sql')).sort();
  const target = names.find(n => n.endsWith('_owner_order_decision.sql'));
  assert.ok(target, 'owner_order_decision migration exists');
  assert.equal(target, names.at(-1), 'the decision migration is the newest');
  const apply = async name => db.transaction(async tx =>
    tx.exec(await readFile(new URL(name, MIGRATIONS), 'utf8')));
  for (const name of names.filter(n => n < target)) await apply(name);

  // ---- Existing data, written before the migration ----
  const hashes = ['a', 'b', 'c', 'd'].map(c => c.repeat(64));
  for (const [i, hash] of hashes.entries()) {
    const created = (await asService('select public.customer_order_submit($1,$2,$3::jsonb) as r',
      [hash, `{"p":${i}}`, JSON.stringify(draft())]))[0].r;
    assert.equal(created.outcome, 'created');
  }
  const [pendingA, pendingB, , legacyApproved] = await Promise.all(hashes.map(read));
  // A decision made before this feature, the way staff could already write it.
  await db.exec(`update public.orders set status='approved', decided_at=now(), decision_note='ישן'
    where id=${legacyApproved.order.id}`);
  await db.exec(`insert into public.customers(full_name, phone) values ('draft', '1');
    insert into public.events(customer_id, event_type, event_date, adults)
      select max(id), 'test', '2030-02-01', 2 from public.customers;
    insert into public.orders(customer_id, event_id, fulfillment_type, requested_at)
      select e.customer_id, e.id, 'pickup', '2030-02-01T10:00:00Z' from public.events e
      order by e.id desc limit 1;`);
  const draftId = (await orders('id, status')).find(o => o.status === 'draft').id;
  const beforeMigration = await everything();
  const receiptsBefore = await Promise.all(hashes.map(read));

  await apply(target);
  console.log('APPLIED:', target);

  assert.deepEqual(await everything(), beforeMigration, 'the migration changes no rows or policies');
  assert.deepEqual(await Promise.all(hashes.map(read)), receiptsBefore, 'legacy receipts read the same');
  console.log('PASS: existing orders, receipts and RLS policies unchanged by the migration.');

  // ---- Who can call it, and what service_role can now change ----
  const call = 'select public.owner_order_decide(1, \'approved\', 1, \'\')';
  await assert.rejects(asRole('anon', {}, call), /permission denied for function/);
  await assert.rejects(asRole('authenticated', OWNER, call), /permission denied for function/);
  const fn = (await db.query(`select p.prosecdef, p.proconfig from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'owner_order_decide'`)).rows;
  assert.deepEqual(fn, [{ prosecdef: false, proconfig: ['search_path=""'] }]);
  const executors = (await db.query(`select r.rolname from pg_roles r
    where has_function_privilege(r.oid, 'public.owner_order_decide(bigint,text,bigint,text)', 'execute')
      and r.rolname in ('anon', 'authenticated', 'service_role', 'public')`)).rows.map(r => r.rolname);
  assert.deepEqual(executors, ['service_role']);
  const updatable = (await db.query(`select column_name from information_schema.columns
    where table_schema = 'public' and table_name = 'orders'
      and has_column_privilege('service_role', 'public.orders', column_name, 'update')
    order by column_name`)).rows.map(r => r.column_name);
  assert.deepEqual(updatable, ['decided_at', 'decision_note', 'status', 'version']);
  for (const name of [...UNTOUCHED, 'dishes', 'delivery_zones']) {
    const { u } = (await db.query(`select has_table_privilege('service_role', 'public.${name}',
      'update') or has_table_privilege('service_role', 'public.${name}', 'delete') as u`)).rows[0];
    assert.equal(u, false, `service_role cannot update or delete ${name}`);
  }
  await assert.rejects(asService('update public.orders set total_minor = 1'), /permission denied/);
  await assert.rejects(asService('update public.order_items set unit_price_minor = 1'), /permission denied/);
  await assert.rejects(asService("update public.events set event_type = 'x'"), /permission denied/);
  // Owner table access through RLS keeps working exactly as before.
  await asRole('authenticated', OWNER, 'select id from public.orders');
  console.log('PASS: only service_role may execute; it may update just the four decision columns.');

  // ---- Decisions ----
  const a = pendingA.order.id;
  const approved = await decide(a, 'approved', 1, 'מאושר');
  assert.equal(approved.decided, true);
  assert.deepEqual(Object.keys(approved.order).sort(),
    ['decided_at', 'decision_note', 'id', 'status', 'version']);
  assert.equal(approved.order.id, a);
  assert.equal(approved.order.status, 'approved');
  assert.equal(approved.order.version, 2);
  assert.equal(approved.order.decision_note, 'מאושר');
  assert.match(approved.order.decided_at, /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$/);

  // Replay and conflicts: no second write, the final row comes back for the backend to judge.
  const afterFirst = await orders(DECISION_COLUMNS.join(', '));
  assert.deepEqual(await decide(a, 'approved', 1, 'מאושר'), { decided: false, order: approved.order });
  assert.deepEqual(await decide(a, 'rejected', 1, 'מאושר'), { decided: false, order: approved.order });
  assert.deepEqual(await decide(a, 'rejected', 2, ''), { decided: false, order: approved.order });
  assert.deepEqual(await orders(DECISION_COLUMNS.join(', ')), afterFirst, 'version moved once');

  // Stale version on a pending order: nothing changes.
  const b = pendingB.order.id;
  const stale = await decide(b, 'rejected', 5, '');
  assert.equal(stale.decided, false);
  assert.equal(stale.order.status, 'pending_approval');
  assert.equal(stale.order.version, 1);
  assert.equal(stale.order.decided_at, null);
  // Rejection with a blank note stores NULL.
  const rejected = await decide(b, 'rejected', 1, '');
  assert.equal(rejected.decided, true);
  assert.deepEqual([rejected.order.status, rejected.order.version, rejected.order.decision_note],
    ['rejected', 2, null]);

  // Draft, already decided legacy order, and a missing order.
  assert.equal((await decide(draftId, 'approved', 1)).decided, false);
  assert.equal((await orders('status')).filter(o => o.status === 'draft').length, 1);
  const legacy = await decide(legacyApproved.order.id, 'rejected', 1, '');
  assert.equal(legacy.decided, false);
  assert.equal(legacy.order.decision_note, 'ישן');
  assert.deepEqual(await decide(999999, 'approved', 1), { decided: false, order: null });

  // Input the backend never sends is still refused by the database.
  await assert.rejects(decide(a + 100, 'pending_approval', 1), /invalid decision/);
  await assert.rejects(decide(a + 100, null, 1), /invalid decision/);
  await assert.rejects(decide(b, 'approved', 1, 'x'.repeat(2001)), /too long/);
  // The transition trigger still guards a direct write by service_role.
  await assert.rejects(asService(`update public.orders set status = 'rejected' where id = ${a}`),
    /invalid order status transition/);
  console.log('PASS: approve, reject, identical replay, conflicts, stale version, draft and missing.');

  // ---- What the customer reads, and what must not move ----
  const receiptA = await read(hashes[0]);
  assert.deepEqual([receiptA.order.status, receiptA.order.version, receiptA.order.decision_note],
    ['approved', 2, 'מאושר']);
  for (const [i, hash] of hashes.entries()) {
    const now = await read(hash);
    const was = receiptsBefore[i];
    assert.deepEqual(now.items, was.items, 'frozen lines');
    assert.equal(now.payload, was.payload, 'frozen submission');
    for (const key of ['id', 'submitted_at', 'subtotal_minor', 'delivery_fee_minor', 'total_minor']) {
      assert.equal(now.order[key], was.order[key], key);
    }
  }
  for (const name of UNTOUCHED) assert.deepEqual(await table(name), beforeMigration[name], name);
  const frozen = await orders(frozenOrderColumns);
  assert.deepEqual(frozen, beforeMigration.orders.map(o => Object.fromEntries(
    frozenOrderColumns.split(', ').map(k => [k, o[k]]))), 'prices, event and timestamps unchanged');
  console.log('PASS: customer reads the decision; prices, items, event and submission unchanged.');

  const decidedRows = await orders();
  await db.close();
  db = await PGlite.create(dataDir);
  assert.deepEqual(await orders(), decidedRows);
  assert.deepEqual(await read(hashes[0]), receiptA);
  assert.deepEqual(await decide(a, 'approved', 1, 'מאושר'), { decided: false, order: approved.order });
  console.log('PASS: decisions and receipts survive database close and reopen.');
} catch (error) {
  console.error(error.message, error.detail ?? '');
  process.exitCode = 1;
} finally {
  await db.close();
  if (!resolve(dataDir).startsWith(tempRoot + sep)) throw new Error('Unexpected test path');
  await rm(dataDir, { recursive: true, force: true });
}
