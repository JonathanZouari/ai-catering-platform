-- Payloads, receipts and storage paths name the code forever, so it cannot change.
create function public.dishes_legacy_code_immutable_fn() returns trigger
language plpgsql security invoker set search_path = '' as $fn$
begin
  if new.legacy_code is distinct from old.legacy_code then
    raise exception 'a dish code cannot change' using errcode = '23514';
  end if;
  return new;
end; $fn$;
revoke all on function public.dishes_legacy_code_immutable_fn() from public, anon, authenticated;
create trigger dishes_legacy_code_immutable before update of legacy_code on public.dishes
for each row execute function public.dishes_legacy_code_immutable_fn();

