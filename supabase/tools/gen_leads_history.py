"""Generate the synthetic historical leads block of supabase/seed_leads.sql.

Deterministic (fixed seed). Rewrites the text between the BEGIN/END HISTORY markers in seed_leads.sql.
    python supabase/tools/gen_leads_history.py            # rewrite the block, print summary statistics
    python supabase/tools/gen_leads_history.py --n 200    # a different size

The closing probability is a hand-written logistic function of the lead's features (see `score`). The data is
SYNTHETIC: a model trained on it learns these assumptions, not real customer behavior. Use it to build and test
the pipeline, then retrain on real closed leads before trusting any score.
"""

import argparse
import csv
import math
import random
from collections import defaultdict
from datetime import UTC, datetime, timedelta
from pathlib import Path

SEED_FILE = Path(__file__).resolve().parent.parent / "seed_leads.sql"
BEGIN, END = "-- BEGIN HISTORY (generated by supabase/tools/gen_leads_history.py)", "-- END HISTORY"

FIRST = ["נועה", "איתי", "מיכל", "יוסי", "רונית", "דן", "שירה", "עמית", "תמר", "אורן", "ליאת", "גיא",
         "הדס", "עידו", "קרן", "בני", "מאיה", "רועי", "יעל", "אסף", "נטע", "תומר", "שני", "אלעד", "גילי"]
LAST = ["לוי", "כהן", "מזרחי", "פרץ", "ביטון", "אברהם", "דהן", "אזולאי", "פרידמן", "גולן", "שפירא",
        "חיים", "רוזן", "סגל", "נחום", "מלכה", "אוחיון", "ברק", "אשכנזי", "שמש"]
MESSAGES = {
    "יום הולדת": ["מחפשים קייטרינג ליום הולדת, בעיקר סלטים ועיקריות.", "יום הולדת בבית, צריך גם מנות לילדים.",
                  "רוצה הצעה ליום הולדת עם קינוחים."],
    "חתונה": ["חתונה קטנה בגן אירועים, מחפשים תפריט מלא.", "מבקשים הצעה לשולחן קבלת פנים ושולחן מתוקים."],
    "אירוע חברה": ["ארוחת צהריים לצוות, יש כמה צמחונים.", "ערב סיום פרויקט, מחפשים משהו קליל.",
                   "כיבוד לכנס של חצי יום."],
    "בר/בת מצווה": ["בר מצווה במשפחה, מחפשים תפריט בשרי.", "בת מצווה, כ-80 איש, רוצים הצעה מסודרת."],
}
# (name, base price per guest in agorot, guests range, share)
EVENT_TYPES = [("יום הולדת", 9000, (12, 50), 0.35), ("חתונה", 16000, (80, 250), 0.15),
               ("אירוע חברה", 12000, (20, 120), 0.30), ("בר/בת מצווה", 13000, (40, 150), 0.20)]
SOURCES = [("landing_form", 0.40, 0.0), ("whatsapp", 0.15, 0.9), ("manual", 0.15, 1.1),
           ("abandoned_order", 0.10, -1.0), ("ai_chat", 0.20, -0.3)]
TYPE_EFFECT = {"יום הולדת": 0.1, "חתונה": -0.5, "אירוע חברה": 0.5, "בר/בת מצווה": 0.2}
# utm (source, medium, campaign) only for landing_form leads; the rest have none
UTMS = [(None, None, None, 0.0, 0.35), ("google", "cpc", "birthday-fall", -0.3, 0.2),
        ("google", "organic", None, 0.4, 0.15), ("facebook", "social", "spring-offer", -0.2, 0.15),
        ("instagram", "social", "stories", -0.1, 0.1), ("newsletter", "email", "nov-menu", 0.4, 0.05)]


def pick(rng, rows, weight_index):
    r, acc = rng.random(), 0.0
    for row in rows:
        acc += row[weight_index]
        if r < acc:
            return row
    return rows[-1]


def score(source_eff, type_name, ratio, lead_days, guests, has_msg, has_email, utm_eff):
    """Log-odds of winning. ratio = budget per guest / typical price per guest (None = no budget given)."""
    z = -1.0 + source_eff + TYPE_EFFECT[type_name] + utm_eff
    z += -0.6 if ratio is None else (ratio - 1.0) * 3.0
    if lead_days is None:
        z -= 0.8
    elif lead_days < 5:
        z -= 1.2
    elif lead_days <= 90:
        z += 0.5
    elif lead_days > 150:
        z -= 0.7
    if guests > 200:
        z -= 0.4
    z += 0.5 if has_msg else 0.0
    z += 0.3 if has_email else 0.0
    return z


def lost_reason(rng, ratio, lead_days):
    if ratio is not None and ratio < 0.85:
        return "המחיר גבוה מהתקציב"
    if lead_days is not None and lead_days < 5:
        return "אין זמינות בתאריך"
    return rng.choice(["בחרו קייטרינג אחר", "לא ענה לאחר כמה ניסיונות", "האירוע בוטל", "בחרו קייטרינג אחר"])


def sql_str(v):
    return "null" if v is None else "'" + str(v).replace("'", "''") + "'"


def generate(n, seed=42):
    rng = random.Random(seed)
    rows, stats = [], defaultdict(lambda: [0, 0])
    for i in range(1, n + 1):
        type_name, base, (g_lo, g_hi), _ = pick(rng, EVENT_TYPES, 3)
        source, _, source_eff = pick(rng, SOURCES, 1)
        utm = pick(rng, UTMS, 4) if source == "landing_form" else (None, None, None, 0.0, 0)
        guests = rng.randint(g_lo, g_hi)
        ratio = round(0.6 + 0.9 * rng.random(), 2)
        budget = round(guests * base * ratio / 100) * 100 if rng.random() > 0.25 else None
        eff_ratio = ratio if budget is not None else None
        lead_days = None if rng.random() < 0.15 else 3 + int(rng.random() ** 2 * 200)
        has_msg = rng.random() < 0.5
        has_email = rng.random() < 0.6
        consent = rng.random() < 0.3
        z = score(source_eff, type_name, eff_ratio, lead_days, guests, has_msg, has_email, utm[3])
        p = 1 / (1 + math.exp(-z))
        won = rng.random() < p
        age_days = rng.randint(25, 730)
        age_hours = rng.randint(0, 23)
        name = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
        row = (
            f"hist-lead-{i:03d}", name, f"+9725010{i:04d}",
            f"hist{i:03d}@example.com" if has_email else None, source, utm[0], utm[1], utm[2], type_name,
            lead_days, guests, budget, rng.choice(MESSAGES[type_name]) if has_msg else None,
            "won" if won else "lost", None if won else lost_reason(rng, eff_ratio, lead_days),
            consent, f"{age_days} days {age_hours} hours",
        )
        rows.append(row)
        for key in (("source", source), ("type", type_name)):
            stats[key][0] += 1
            stats[key][1] += won
        stats[("all", "all")][0] += 1
        stats[("all", "all")][1] += won
    return rows, stats


def render(rows):
    lines = [BEGIN,
             f"-- {len(rows)} closed leads (won/lost) spread over the last two years. Phones +9725010xxxx, emails @example.com.",
             "-- event_date is relative to the lead's own created_at (lead_days after it).",
             "insert into public.leads",
             "  (id, full_name, phone, email, source, utm_source, utm_medium, utm_campaign,",
             "   event_type_id, event_date, approx_guests, budget_estimate, message, status, lost_reason,",
             "   consent_marketing, consent_at, created_at)",
             "select v.id, v.full_name, v.phone, v.email, v.source, v.utm_source, v.utm_medium, v.utm_campaign,",
             "       (select e.id from public.event_types e where e.name = v.event_type),",
             "       case when v.lead_days is null then null else (now() - v.age)::date + v.lead_days end,",
             "       v.guests, v.budget, v.message, v.status, v.lost_reason,",
             "       v.consent, case when v.consent then now() - v.age else null end,",
             "       now() - v.age",
             "from (values"]
    out = []
    for r in rows:
        (id_, name, phone, email, source, us, um, uc, et, ld, g, b, msg, status, lr, consent, age) = r
        out.append(
            f"  ({sql_str(id_)},{sql_str(name)},{sql_str(phone)},{sql_str(email)},{sql_str(source)},"
            f"{sql_str(us)},{sql_str(um)},{sql_str(uc)},{sql_str(et)},{'null' if ld is None else ld},{g},"
            f"{'null' if b is None else b},{sql_str(msg)},{sql_str(status)},{sql_str(lr)},"
            f"{'true' if consent else 'false'},interval '{age}')")
    lines.append(",\n".join(out))
    lines.append(") as v(id, full_name, phone, email, source, utm_source, utm_medium, utm_campaign, event_type,")
    lines.append("       lead_days, guests, budget, message, status, lost_reason, consent, age);")
    lines.append(END)
    return "\n".join(lines)


CSV_COLUMNS = ["id", "created_at", "source", "utm_medium", "event_type", "guests", "budget_estimate",
               "budget_per_guest", "lead_time_days", "missing_event_date", "has_email", "has_message",
               "consent_marketing", "is_won"]  # fmt: skip


def write_training_csv(rows, path, anchor):
    """Same columns as the lead_training_data view, so the ML pipeline can train without a database."""
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=CSV_COLUMNS)
        w.writeheader()
        for r in rows:
            (id_, _n, _p, email, source, _us, um, _uc, et, ld, g, b, msg, status, _lr, consent, age) = r
            days, hours = int(age.split()[0]), int(age.split()[2])
            created = anchor - timedelta(days=days, hours=hours)
            w.writerow({
                "id": id_, "created_at": created.isoformat(), "source": source, "utm_medium": um or "",
                "event_type": et, "guests": g, "budget_estimate": "" if b is None else b,
                "budget_per_guest": "" if b is None else b // g,  # integer division, like the view
                "lead_time_days": "" if ld is None else ld, "missing_event_date": str(ld is None).lower(),
                "has_email": str(email is not None).lower(), "has_message": str(msg is not None).lower(),
                "consent_marketing": str(consent).lower(), "is_won": str(status == "won").lower(),
            })  # fmt: skip


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=150)
    ap.add_argument("--csv", help="also write the training view columns to this CSV (for app.ml.train)")
    ap.add_argument("--anchor", help="'now' for the CSV created_at values, ISO date (default: today)")
    args = ap.parse_args()
    rows, stats = generate(args.n)
    if args.csv:
        anchor = datetime.fromisoformat(args.anchor).replace(tzinfo=UTC) if args.anchor else datetime.now(UTC)
        write_training_csv(rows, args.csv, anchor)
    text = SEED_FILE.read_text(encoding="utf-8")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    SEED_FILE.write_text(text[:start] + render(rows) + text[end:], encoding="utf-8", newline="\n")
    for (kind, key), (total, wins) in sorted(stats.items()):
        print(f"{kind:7} {key:18} n={total:3}  win rate={wins / total:.0%}")


if __name__ == "__main__":
    main()
