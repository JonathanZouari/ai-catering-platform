                     WHERE equipment_item_id = NEW.equipment_item_id AND order_id = NEW.order_id), 0)
           < NEW.quantity THEN RAISE EXCEPTION 'more equipment returned or lost than was dispatched for this order' USING ERRCODE='23514'; END IF;
    END IF;
    RETURN NEW;
END; $fn$;

