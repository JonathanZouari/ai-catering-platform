CREATE TABLE public.customers (
    id bigint generated by default as identity PRIMARY KEY,
    full_name   TEXT NOT NULL CHECK (length(trim(full_name)) > 0),
    email       TEXT  UNIQUE CHECK (email IS NULL OR email LIKE '%_@_%'),
    phone       TEXT CHECK (phone IS NULL OR length(trim(phone)) > 0),
    created_at timestamptz NOT NULL DEFAULT now()
                ,
    updated_at timestamptz NOT NULL DEFAULT now()
                ,
    CHECK (email IS NOT NULL OR phone IS NOT NULL)
);

CREATE TABLE public.addresses (
    id bigint generated by default as identity PRIMARY KEY,
    customer_id   bigint REFERENCES public.customers (id),
    label         TEXT,
    street        TEXT NOT NULL CHECK (length(trim(street)) > 0),
    house_number  TEXT,
    apartment     TEXT,
    floor         TEXT,
    city          TEXT NOT NULL CHECK (length(trim(city)) > 0),
    postal_code   TEXT,
    access_notes  TEXT,
    created_at timestamptz NOT NULL DEFAULT now()
                  ,
    updated_at timestamptz NOT NULL DEFAULT now()
                  ,
    UNIQUE (id, customer_id)
);

CREATE TABLE public.events (
    id bigint generated by default as identity PRIMARY KEY,
    customer_id        bigint NOT NULL REFERENCES public.customers (id),
    event_type         TEXT NOT NULL CHECK (length(trim(event_type)) > 0),
    event_date date NOT NULL ,
    adults             bigint NOT NULL DEFAULT 0 CHECK (adults >= 0),
    children           bigint NOT NULL DEFAULT 0 CHECK (children >= 0),
    vegetarian_guests  bigint NOT NULL DEFAULT 0 CHECK (vegetarian_guests >= 0),
    vegan_guests       bigint NOT NULL DEFAULT 0 CHECK (vegan_guests >= 0),
    restricted_guests  bigint NOT NULL DEFAULT 0 CHECK (restricted_guests >= 0),
    dietary_notes      TEXT,
    created_at timestamptz NOT NULL DEFAULT now()
                       ,
    updated_at timestamptz NOT NULL DEFAULT now()
                       ,
    CHECK (adults + children > 0),
    UNIQUE (id, customer_id)
);

CREATE TABLE public.orders (
    id bigint generated by default as identity PRIMARY KEY,
    customer_id          bigint NOT NULL REFERENCES public.customers (id),
    event_id             bigint NOT NULL UNIQUE,
    status               TEXT NOT NULL DEFAULT 'draft'
                         CHECK (status IN ('draft', 'pending_approval', 'approved', 'rejected')),
    version              bigint NOT NULL DEFAULT 1 CHECK (version >= 1),
    fulfillment_type     TEXT NOT NULL CHECK (fulfillment_type IN ('pickup', 'delivery')),
    requested_at timestamptz NOT NULL
                         ,
    delivery_address_id  bigint,
    currency             TEXT NOT NULL DEFAULT 'ILS'
                         CHECK (length(currency) = 3 AND currency = upper(currency)),
    subtotal_minor       bigint CHECK (subtotal_minor IS NULL OR subtotal_minor >= 0),
    delivery_fee_minor   bigint CHECK (delivery_fee_minor IS NULL OR delivery_fee_minor >= 0),
    total_minor          bigint CHECK (total_minor IS NULL OR total_minor >= 0),
    submitted_at timestamptz ,
    decided_at timestamptz ,
    decision_note        TEXT,
    created_at timestamptz NOT NULL DEFAULT now()
                         ,
    updated_at timestamptz NOT NULL DEFAULT now()
                         ,

    FOREIGN KEY (event_id, customer_id) REFERENCES public.events (id, customer_id),
    FOREIGN KEY (delivery_address_id, customer_id) REFERENCES public.addresses (id, customer_id),
    UNIQUE (id, currency),
    CHECK (fulfillment_type = 'delivery' OR delivery_address_id IS NULL),
    CHECK (fulfillment_type = 'delivery' OR delivery_fee_minor IS NULL OR delivery_fee_minor = 0),

    CHECK (status = 'draft' OR fulfillment_type = 'pickup' OR delivery_address_id IS NOT NULL),
    CHECK (status = 'draft' OR (subtotal_minor IS NOT NULL AND delivery_fee_minor IS NOT NULL
                                AND total_minor IS NOT NULL AND submitted_at IS NOT NULL)),
    CHECK (total_minor IS NULL OR (subtotal_minor IS NOT NULL AND delivery_fee_minor IS NOT NULL
                                   AND total_minor = subtotal_minor + delivery_fee_minor)),
    CHECK ((status IN ('approved', 'rejected')) = (decided_at IS NOT NULL))
);

