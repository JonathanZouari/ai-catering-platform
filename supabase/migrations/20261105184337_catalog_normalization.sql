    CHECK (is_vegan IS NOT TRUE OR is_vegetarian IS NOT FALSE)
);

-- verified_at stays NULL: the old documents do not record who checked a value or when.
insert into public.dish_dietary(dish_id, kashrut_class, is_vegetarian, is_vegan)
select b.dish_id,
  case when b.metadata->>'kashrut' in ('meat', 'dairy', 'pareve') then b.metadata->>'kashrut' end,
  case when facts.vegan and facts.vegetarian is false then null else facts.vegetarian end,
  case when facts.vegan and facts.vegetarian is false then null else facts.vegan end
from private.dish_metadata_backup b
cross join lateral (select
  case when jsonb_typeof(b.metadata->'vegetarian') = 'boolean' then (b.metadata->>'vegetarian')::boolean end as vegetarian,
  case when jsonb_typeof(b.metadata->'vegan') = 'boolean' then (b.metadata->>'vegan')::boolean end as vegan
) facts;

