CREATE FUNCTION public.equipment_movements_out_not_negative_fn() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = '' AS $fn$
BEGIN
    IF NEW.movement_type IN ('return', 'lost_at_event') THEN
        PERFORM 1 FROM public.equipment_items WHERE id=NEW.equipment_item_id FOR NO KEY UPDATE;
        IF NOT FOUND THEN RAISE EXCEPTION 'equipment item is not visible to this role' USING ERRCODE='23514'; END IF;
