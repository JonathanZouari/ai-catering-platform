// Isolated database tests. No hosted database or credentials are accessed.
import {readFile, readdir, mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join, resolve, sep} from 'node:path';
import assert from 'node:assert/strict';
import {PGlite} from '../.test-tools/pglite/dist/index.js';
import {checkCustomerOrderRpc} from './customer-order-rpc.mjs';
import {TABLES,RELATIONS} from '../../frontend/admin/js/schema.js';
const tempRoot = resolve(tmpdir());
const dataDir = await mkdtemp(join(tempRoot,'catering-mvp-test-'));
let db = await PGlite.create(dataDir);
try {
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
    CREATE SCHEMA auth; GRANT USAGE ON SCHEMA auth TO anon, authenticated;
    CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS
      $$ SELECT coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
    CREATE SCHEMA storage;
    CREATE TABLE storage.buckets(id text PRIMARY KEY,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    CREATE TABLE storage.objects(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,bucket_id text REFERENCES storage.buckets(id),name text);
    ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
    GRANT USAGE ON SCHEMA storage TO authenticated;
    GRANT SELECT,INSERT,UPDATE,DELETE ON storage.objects TO authenticated;
    GRANT USAGE ON ALL SEQUENCES IN SCHEMA storage TO authenticated;
    CREATE PUBLICATION supabase_realtime;`);
  for (const name of (await readdir(new URL('../migrations/',import.meta.url))).sort()) {
    if (name < '20261105182903' || !name.endsWith('.sql')) continue;
    await db.transaction(async tx => tx.exec(await readFile(new URL('../migrations/'+name,import.meta.url),'utf8')));
    console.log('APPLIED:',name);
  }
  const tables = (await db.query(`SELECT tablename,rowsecurity FROM pg_tables WHERE schemaname='public'`)).rows;
  for(const name of ['employees','payments','ingredients','equipment_items','deliveries']) {
    assert.equal(tables.some(t=>t.tablename===name),false,`${name} is excluded from MVP`);
  }
  assert.ok(tables.every(t=>t.rowsecurity),'all public tables use RLS');
  assert.deepEqual(TABLES.map(t=>t.name).sort(),tables.map(t=>t.tablename).sort());
  for(const table of TABLES) {
    const columns=(await db.query("SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name=$1",[table.name])).rows;
    assert.deepEqual(table.columns.map(c=>c.name).sort(),columns.map(c=>c.column_name).sort(),table.name);
  }
  const actualRelations=(await db.query(`SELECT source.relname AS "from",target.relname AS "to",
    array_agg(a.attname::text ORDER BY u.i) AS columns,array_agg(b.attname::text ORDER BY u.i) AS "toColumns"
    FROM pg_constraint k JOIN pg_class source ON source.oid=k.conrelid
    JOIN pg_namespace ns ON ns.oid=source.relnamespace
    JOIN pg_class target ON target.oid=k.confrelid
    CROSS JOIN LATERAL generate_subscripts(k.conkey,1) u(i)
    JOIN pg_attribute a ON a.attrelid=source.oid AND a.attnum=k.conkey[u.i]
    JOIN pg_attribute b ON b.attrelid=target.oid AND b.attnum=k.confkey[u.i]
    WHERE ns.nspname='public' AND k.contype='f'
    GROUP BY k.oid,source.relname,target.relname`)).rows;
  const relationKey=r=>`${r.from}(${r.columns})->${r.to}(${r.toColumns})`;
  assert.deepEqual(RELATIONS.map(relationKey).sort(),actualRelations.map(relationKey).sort());
  const keys=(await db.query(`SELECT c.relname,a.attname,format_type(a.atttypid,a.atttypmod) AS type
    FROM pg_constraint k JOIN pg_class c ON c.oid=k.conrelid
    JOIN pg_namespace n ON n.oid=c.relnamespace
    JOIN pg_attribute a ON a.attrelid=c.oid AND a.attnum=ANY(k.conkey)
    WHERE n.nspname='public' AND k.contype IN ('p','f')`)).rows;
  assert.ok(keys.length>0);
  assert.deepEqual(keys.filter(k=>k.type!=='bigint'),[],'all domain PK/FK columns use bigint');
  const role = (name, claims, sql) => db.transaction(async tx=>{
    await tx.exec(`SET LOCAL ROLE ${name}`);
    await tx.query("SELECT set_config('request.jwt.claims',$1,true)",[JSON.stringify(claims)]);
    return tx.exec(sql);
  });
  await assert.rejects(role('anon',{},'SELECT * FROM public.time_slots'),/permission denied/);
  await assert.rejects(role('authenticated',{user_metadata:{role:'catering_owner'}},
    "INSERT INTO public.blocked_dates(date) VALUES ('2027-01-01')"),/row-level security/);
  await role('authenticated',{app_metadata:{role:'catering_owner'}},
    "INSERT INTO public.time_slots(fulfillment_type,weekday,start_time,end_time) VALUES ('pickup',0,'10:00','12:00'); INSERT INTO public.blocked_dates(date) VALUES ('2027-01-01')");
  await assert.rejects(db.exec("INSERT INTO public.time_slots(fulfillment_type,start_time,end_time) VALUES ('pickup','12:00','10:00')"),/check constraint/);
  for(const table of ['ai_conversations','ai_messages','ai_change_proposals']) {
    await assert.rejects(role('authenticated',{app_metadata:{role:'catering_owner'}},`SELECT * FROM public.${table}`),/permission denied/);
  }
  await db.exec(`INSERT INTO customers(full_name,phone) VALUES ('synthetic','1');
    INSERT INTO events(customer_id,event_type,event_date,adults) VALUES (1,'test','2027-01-02',2),(1,'test','2027-01-03',2);
    INSERT INTO orders(customer_id,event_id,fulfillment_type,requested_at) VALUES (1,1,'pickup','2027-01-02T10:00:00Z'),(1,2,'pickup','2027-01-03T10:00:00Z');
    INSERT INTO ai_conversations(order_id) VALUES (1);
    INSERT INTO ai_messages(conversation_id,role,content) VALUES (1,'user','{"text":"test"}');`);
  await assert.rejects(db.exec(`INSERT INTO ai_change_proposals(order_id,conversation_id,base_order_version,changes,price_before_minor,price_after_minor)
    VALUES (2,1,1,'[{"type":"set_quantity"}]',100,200)`),/foreign key constraint/);
  await db.exec(`INSERT INTO ai_change_proposals(order_id,conversation_id,base_order_version,changes,price_before_minor,price_after_minor)
    VALUES (1,1,1,'[{"type":"set_quantity"}]',100,200)`);
  await assert.rejects(db.exec("UPDATE ai_change_proposals SET status='approved',decided_at=now() WHERE order_id=1"),/check constraint/);
  await db.exec("UPDATE ai_change_proposals SET status='approved',decided_at=now(),executed_at=now() WHERE order_id=1");
  await assert.rejects(db.exec("DELETE FROM ai_change_proposals WHERE order_id=1"),/immutable/);
  const snapshot=await db.query('SELECT version,status FROM orders WHERE id=1');
  assert.deepEqual(snapshot.rows[0],{version:1,status:'draft'},'recording a proposal is not execution');
  await checkCustomerOrderRpc(db);
  await db.exec("UPDATE dish_categories SET is_active=false WHERE legacy_code='salads'");
  const catalog=(await db.query('SELECT customer_catalog() c')).rows[0].c;
  assert.ok(!catalog.dishes.some(d=>d.metadata.categoryId==='salads'));
  const receipt = (await db.query("SELECT customer_order_read($1) AS r",['a'.repeat(64)])).rows[0].r;
  await db.close();
  db = await PGlite.create(dataDir);
  await db.exec('SET ROLE service_role');
  assert.deepEqual((await db.query("SELECT customer_order_read($1) AS r",['a'.repeat(64)])).rows[0].r,receipt);
  await db.exec('RESET ROLE');
  console.log('PASS: saved receipt survives database close and reopen.');
  console.log('PASS: MVP scope, RLS, scheduling constraints, proposal ownership and history.');
} catch(error) {
  console.error(error.message, error.detail ?? '');
  process.exitCode=1;
} finally {
  await db.close();
  if (!resolve(dataDir).startsWith(tempRoot+sep)) throw new Error('Unexpected test path');
  await rm(dataDir,{recursive:true,force:true});
}
