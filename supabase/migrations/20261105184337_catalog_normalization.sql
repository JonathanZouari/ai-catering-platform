-- Normalizes the dish catalog and moves dishes, delivery zones and submissions to bigint keys.
-- Applies to both the initialized course project and a fresh MVP baseline. The migration runner owns
-- the transaction, so any failure leaves the old schema and every row untouched.
--
-- Compatibility: the API, the browser, stored submission payloads and storage paths all name dishes
-- with codes such as d1. They keep doing so through dishes.legacy_code, which is unique and immutable.
-- Every database key and foreign key is bigint. p_order items still send the code as "dish_id".
--
-- Nothing rewrites submission rows or the snapshot columns of order_items, so receipts, token hashes
-- and byte-for-byte retry comparisons are unaffected.
--
-- Published tables need a replica identity to accept UPDATE, so all backfills run before the
-- primary keys they rely on are swapped.
set local lock_timeout = '5s';
lock table public.dishes, public.delivery_zones, public.order_items, public.order_submissions
  in access exclusive mode;

-- A dish the migration cannot read safely stops it; a guessed unit or name would change quotes.
do $preflight$
declare
  bad text;
begin
  select string_agg(d.id, ', ' order by d.id) into bad
  from public.dishes d
  where not coalesce(
    d.id ~ '^[A-Za-z0-9_-]{1,64}$'
    and jsonb_typeof(d.metadata) = 'object'
    and length(trim(d.metadata->>'name')) > 0
    and d.metadata->>'categoryId' ~ '^[A-Za-z0-9_-]{1,64}$'
    and d.metadata->>'unit' in ('tray', 'kg', 'item', 'guest')
    and coalesce(jsonb_typeof(d.metadata->'allergens'), 'null') in ('array', 'null')
    and coalesce(jsonb_typeof(d.metadata->'perGuest'), 'null') in ('number', 'null')
    and coalesce((d.metadata->>'perGuest')::numeric > 0, true),
    false);
  if bad is not null then
    raise exception 'catalog normalization: fix these dishes first: %', bad using errcode = '23514';
  end if;
end; $preflight$;

