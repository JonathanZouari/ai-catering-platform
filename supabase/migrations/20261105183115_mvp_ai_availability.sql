-- MVP schema foundation. This does not implement or enable an AI executor.
-- Existing quotations are preserved; scheduling links are optional for historical rows.
CREATE TABLE public.time_slots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fulfillment_type text NOT NULL CHECK (fulfillment_type IN ('pickup','delivery')),
  weekday smallint CHECK (weekday BETWEEN 0 AND 6),
  start_time time NOT NULL,
  end_time time NOT NULL,
  capacity integer CHECK (capacity > 0),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (end_time > start_time)
);
CREATE TABLE public.blocked_dates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date date NOT NULL UNIQUE,
  reason text,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.orders ADD COLUMN time_slot_id bigint REFERENCES public.time_slots(id);
CREATE INDEX orders_time_slot_id_idx ON public.orders(time_slot_id);

CREATE TABLE public.ai_conversations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.orders(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id, order_id)
);
CREATE INDEX ai_conversations_order_id_idx ON public.ai_conversations(order_id);
CREATE TABLE public.ai_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id bigint NOT NULL REFERENCES public.ai_conversations(id),
  role text NOT NULL CHECK (role IN ('user','assistant','tool')),
  content jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ai_messages_conversation_id_idx ON public.ai_messages(conversation_id);
CREATE TABLE public.ai_change_proposals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.orders(id),
  conversation_id bigint,
  base_order_version bigint NOT NULL CHECK (base_order_version > 0),
  changes jsonb NOT NULL CHECK (jsonb_typeof(changes) = 'array' AND jsonb_array_length(changes) > 0),
  price_before_minor bigint NOT NULL CHECK (price_before_minor >= 0),
  price_after_minor bigint NOT NULL CHECK (price_after_minor >= 0),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','expired','failed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  decided_at timestamptz,
  executed_at timestamptz,
  FOREIGN KEY (conversation_id, order_id) REFERENCES public.ai_conversations(id, order_id),
  CHECK ((status = 'pending') = (decided_at IS NULL)),
  CHECK ((status = 'approved') = (executed_at IS NOT NULL)),
  CHECK (decided_at >= created_at),
  CHECK (executed_at >= decided_at)
);
CREATE INDEX ai_change_proposals_order_id_idx ON public.ai_change_proposals(order_id);
CREATE INDEX ai_change_proposals_conversation_id_idx ON public.ai_change_proposals(conversation_id, order_id);

-- Once execution has been recorded, its audit record cannot be revised or deleted.
-- Version checks and actual order mutations belong to a future customer-approved,
-- transactional execution endpoint; there is deliberately no such RPC in this migration.
CREATE FUNCTION public.guard_executed_ai_proposal() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
BEGIN
  IF OLD.executed_at IS NOT NULL THEN
    RAISE EXCEPTION 'executed AI proposals are immutable';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.guard_executed_ai_proposal() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER ai_proposal_execution_history BEFORE UPDATE OR DELETE ON public.ai_change_proposals
FOR EACH ROW EXECUTE FUNCTION public.guard_executed_ai_proposal();

