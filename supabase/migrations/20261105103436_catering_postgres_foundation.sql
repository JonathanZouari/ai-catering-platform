    SELECT ingredient_id INTO batch_ingredient_id FROM public.ingredient_batches WHERE id=NEW.batch_id FOR NO KEY UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'ingredient batch is not visible to this role' USING ERRCODE='23514'; END IF;
