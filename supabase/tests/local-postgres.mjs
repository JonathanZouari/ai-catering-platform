// Isolated PGlite SQL execution. Auth/Storage schemas below are test stubs,
// not a substitute for hosted Supabase Auth, Storage, Realtime or concurrency tests.
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { PGlite } from '../.test-tools/pglite/dist/index.js';
import { checkCustomerOrderRpc } from './customer-order-rpc.mjs';
const db = await PGlite.create();
try {
  await db.exec(`
    create role anon;
    create role authenticated;
    create role service_role bypassrls;
    create schema auth;
    grant usage on schema auth to anon, authenticated;
    create function auth.jwt() returns jsonb language sql stable as
      $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
    create schema storage;
    create table storage.buckets(id text primary key,name text,public boolean,
      file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id bigint generated by default as identity primary key,
      bucket_id text references storage.buckets(id),name text);
    alter table storage.objects enable row level security;
    grant usage on schema storage to authenticated;
    grant select,insert,update,delete on storage.objects to authenticated;
    grant usage on all sequences in schema storage to authenticated;
    create publication supabase_realtime;
  `);
  for (const name of ['20261105103436_catering_postgres_foundation.sql',
    '20261105104438_catering_storage_realtime_demo.sql',
    '20261105132842_customer_order_rpc.sql']) {
    const sql = await readFile(new URL('../migrations/'+name,import.meta.url),'utf8');
    await db.transaction(async tx => { await tx.exec(sql); });
    console.log('APPLIED locally:',name);
  }
  const checks = await db.query(`select
    (select count(*) from public.customers) as customers,
    (select count(*) from public.orders) as orders,
    (select count(*) from public.deliveries) as deliveries,
    (select count(*) from public.payments) as payments,
    (select count(*) from pg_publication_tables where pubname='supabase_realtime') as realtime_tables`);
  console.log('Synthetic seed counts:',JSON.stringify(checks.rows));
  assert.deepEqual(checks.rows[0], {customers:3,orders:3,deliveries:2,payments:2,realtime_tables:15});
  const testSql = await readFile(new URL('./foundation.sql',import.meta.url),'utf8');
  await db.exec(testSql);
  const asRole = (role, claims, sql) => db.transaction(async tx => {
    await tx.exec(`set local role ${role}`);
    await tx.query("select set_config('request.jwt.claims',$1,true)",[JSON.stringify(claims)]);
    return tx.exec(sql);
  });
  await assert.rejects(asRole('anon',{},'select * from public.customers'),/permission denied/);
  const unprivileged = await asRole('authenticated',
    {user_metadata:{role:'catering_owner'}},'select * from public.customers');
  assert.equal(unprivileged[0].rows.length,0,'user metadata cannot grant a staff role');
  await assert.rejects(asRole('authenticated',{},
    "insert into storage.objects(bucket_id,name) values('dish-images','dishes/d1/test.png')"),/row-level security/);
  const staff = {app_metadata:{role:'catering_manager'}};
  await asRole('authenticated',staff,
    "insert into storage.objects(bucket_id,name) values('dish-images','dishes/d1/test.png')");
  await assert.rejects(asRole('authenticated',staff,
    "insert into storage.objects(bucket_id,name) values('dish-images','dishes/missing/test.png')"),/row-level security/);
  await assert.rejects(asRole('authenticated',staff,
    "update public.dishes set image_path='dishes/d2/test.png' where id='d1'"),/check constraint/);
  assert.equal((await db.query("select public from storage.buckets where id='dish-images'")).rows[0].public,false);
  await checkCustomerOrderRpc(db);
  console.log('PASS local PostgreSQL foundation + seed + RLS + image path + customer order RPC assertions.');
  console.log('Not tested: hosted Auth/Storage/Realtime APIs, multi-connection concurrency.');
} catch (error) {
  console.error('FAIL',error.message, error.detail || '', error.where || '');
  process.exitCode=1;
} finally { await db.close(); }
