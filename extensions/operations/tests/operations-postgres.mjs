// Isolated database tests. No hosted database or credentials are accessed.
import {readFile, readdir, mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join, resolve, sep} from 'node:path';
import assert from 'node:assert/strict';
import {PGlite} from '../../../supabase/.test-tools/pglite/dist/index.js';

const tempRoot = resolve(tmpdir());
const dataDir = await mkdtemp(join(tempRoot,'catering-mvp-test-'));
let db = await PGlite.create(dataDir);
try {
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
    CREATE SCHEMA auth; GRANT USAGE ON SCHEMA auth TO anon, authenticated;
    CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS
      $$ SELECT coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
    CREATE SCHEMA storage;
    CREATE TABLE storage.buckets(id text PRIMARY KEY,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    CREATE TABLE storage.objects(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,bucket_id text REFERENCES storage.buckets(id),name text);
    ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
    GRANT USAGE ON SCHEMA storage TO authenticated;
    GRANT SELECT,INSERT,UPDATE,DELETE ON storage.objects TO authenticated;
    GRANT USAGE ON ALL SEQUENCES IN SCHEMA storage TO authenticated;
    CREATE PUBLICATION supabase_realtime;`);
  for (const name of (await readdir(new URL('../../../supabase/migrations/',import.meta.url))).sort()) {
    if (name < '20261105182903' || !name.endsWith('.sql')) continue;
    await db.transaction(async tx => tx.exec(await readFile(new URL('../../../supabase/migrations/'+name,import.meta.url),'utf8')));
    console.log('APPLIED:',name);
  }

  const extension = await readFile(new URL('../supabase/migrations/20261105185608_optional_operations_extension.sql',import.meta.url),'utf8');
  await db.transaction(tx=>tx.exec(extension));
  await db.exec("INSERT INTO employees(full_name,role) VALUES ('synthetic','driver')");
  await db.transaction(tx=>tx.exec(extension));
  assert.equal((await db.query('SELECT count(*)::int n FROM employees')).rows[0].n,1);
  assert.equal((await db.query("SELECT count(*)::int n FROM pg_tables WHERE schemaname='public' AND rowsecurity")).rows[0].n,25);
  await db.exec("SET ROLE authenticated; SELECT set_config('request.jwt.claims','{\"app_metadata\":{\"role\":\"catering_owner\"}}',false)");
  assert.equal((await db.query('SELECT full_name FROM employees')).rows[0].full_name,'synthetic');
  await db.query('SELECT * FROM equipment_stock');
  await db.exec("SELECT set_config('request.jwt.claims','{\"user_metadata\":{\"role\":\"catering_owner\"}}',false)");
  assert.equal((await db.query('SELECT * FROM employees')).rows.length,0);
  console.log('PASS: optional extension installs, preserves existing rows and restricts access to owner.');
} catch(error) { console.error(error.message,error.detail ?? ''); process.exitCode=1; }
finally { await db.close(); if(!resolve(dataDir).startsWith(tempRoot+sep)) throw new Error('Unexpected path'); await rm(dataDir,{recursive:true,force:true}); }
